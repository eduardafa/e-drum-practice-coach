#!/usr/bin/env python3
"""
Builds the spoken count's sound file: src/audio/count/count.wav and the
table of where each syllable sits in it, src/audio/countSprite.ts.

The voice is CMU Flite's cmu_us_slt, run through its shared library (the
libflite1 package on Debian and Ubuntu), so nothing is recorded and nothing
needs a voice actor's license. Flite's license allows use and redistribution
without restriction (Copyright (c) 1999-2001 Language Technologies Institute,
Carnegie Mellon University).

Each syllable is spoken on its own, trimmed so the sound starts at once (the
metronome schedules it on the beat, so leading silence would make it late),
given a short fade in and out, normalized, and placed one after another with
a gap of silence. Mono, 16-bit, 16 kHz: speech needs no more, and the file
stays small.

Run from the repository root: python3 scripts/count-voice.py
Standard library only.
"""
import array
import ctypes
import os
import tempfile
import wave

LIB = "/usr/lib/x86_64-linux-gnu/"
VOICE = "slt"
# Spoken a little faster than Flite's normal pace, so a syllable fits between eighth notes.
DURATION_STRETCH = 0.8

# Syllable name (as the app labels the count) -> the text Flite speaks.
SYLLABLES = {
    "1": "one",
    "2": "two",
    "3": "three",
    "4": "four",
    "5": "five",
    "6": "six",
    "7": "seven",
    "&": "and",
    "e": "ee",
    "a": "uh",
    "trip": "trip",
    "let": "let",
}

RATE = 16000
GAP_SEC = 0.05
FADE_IN_SEC = 0.003
FADE_OUT_SEC = 0.02
# A sample this far below the peak counts as silence when trimming.
TRIM_THRESHOLD = 0.03
PEAK = 0.9

OUT_WAV = "src/audio/count/count.wav"
OUT_TS = "src/audio/countSprite.ts"


def load_flite():
    flite = ctypes.CDLL(LIB + "libflite.so.1", mode=ctypes.RTLD_GLOBAL)
    ctypes.CDLL(LIB + "libflite_usenglish.so.1", mode=ctypes.RTLD_GLOBAL)
    ctypes.CDLL(LIB + "libflite_cmulex.so.1", mode=ctypes.RTLD_GLOBAL)
    voice_lib = ctypes.CDLL(LIB + f"libflite_cmu_us_{VOICE}.so.1", mode=ctypes.RTLD_GLOBAL)
    flite.flite_init()
    register = getattr(voice_lib, f"register_cmu_us_{VOICE}")
    register.restype = ctypes.c_void_p
    voice = register(None)
    # cst_voice starts { const char *name; cst_features *features; ... }.
    features = ctypes.c_void_p.from_address(voice + ctypes.sizeof(ctypes.c_void_p)).value
    flite.flite_feat_set_float.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_float]
    flite.flite_feat_set_float(features, b"duration_stretch", DURATION_STRETCH)
    flite.flite_text_to_speech.restype = ctypes.c_float
    flite.flite_text_to_speech.argtypes = [ctypes.c_char_p, ctypes.c_void_p, ctypes.c_char_p]
    return flite, voice


def speak(flite, voice, text, path):
    flite.flite_text_to_speech(text.encode(), voice, path.encode())
    with wave.open(path, "rb") as w:
        assert w.getframerate() == RATE and w.getnchannels() == 1 and w.getsampwidth() == 2
        samples = array.array("h", w.readframes(w.getnframes()))
    return [s / 32768 for s in samples]


def shape(samples):
    peak = max(abs(s) for s in samples)
    loud = [i for i, s in enumerate(samples) if abs(s) >= peak * TRIM_THRESHOLD]
    samples = samples[loud[0] : loud[-1] + 1]
    fade_in = int(FADE_IN_SEC * RATE)
    fade_out = int(FADE_OUT_SEC * RATE)
    n = len(samples)
    return [
        s * (PEAK / peak) * min(1, i / fade_in) * min(1, (n - 1 - i) / fade_out)
        for i, s in enumerate(samples)
    ]


def main():
    flite, voice = load_flite()
    out = array.array("h")
    table = []
    with tempfile.TemporaryDirectory() as tmp:
        for i, (name, text) in enumerate(SYLLABLES.items()):
            samples = shape(speak(flite, voice, text, os.path.join(tmp, f"{i}.wav")))
            table.append((name, len(out) / RATE, len(samples) / RATE))
            out.extend(round(s * 32767) for s in samples)
            out.extend([0] * int(GAP_SEC * RATE))

    os.makedirs(os.path.dirname(OUT_WAV), exist_ok=True)
    with wave.open(OUT_WAV, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(out.tobytes())

    rows = "\n".join(f'  "{name}": {{ start: {start:.4f}, duration: {dur:.4f} }},' for name, start, dur in table)
    with open(OUT_TS, "w") as f:
        f.write(
            "// Generated by scripts/count-voice.py: where each spoken syllable sits in count/count.wav, in seconds.\n"
            "export const COUNT_SPRITE: Readonly<Record<string, { start: number; duration: number }>> = {\n"
            f"{rows}\n"
            "};\n"
        )
    print(f"{OUT_WAV}: {len(out) / RATE:.2f} s, {os.path.getsize(OUT_WAV)} bytes")
    for name, start, dur in table:
        print(f"  {name:5} {dur * 1000:4.0f} ms")


if __name__ == "__main__":
    main()
